#!/usr/bin/env python3
"""Generate the Team1 CSS custom properties and Tailwind 4 theme from design-tokens.json.

design-tokens.json (W3C Design Tokens format) is the single source. This script writes:
  tokens/design-tokens.css   CSS custom properties: static foundations plus dark (default) and light themes
  tokens/tailwind-theme.css  Tailwind CSS v4 theme (@theme) mapped onto those custom properties

Usage:  python3 scripts/build_tokens.py [package-root] [--check]
With --check the script exits 1 when the generated files are out of date instead of writing them.
Standard library only; no network access.
"""

import json
import re
import sys
from pathlib import Path

HEADER = "/* Generated by scripts/build_tokens.py from tokens/design-tokens.json (Team1 Design System {version}). Do not edit by hand. */\n"


def value(node):
    raw = node["$value"]
    kind = node.get("$type")
    if kind == "cubicBezier":
        return "cubic-bezier({})".format(", ".join(str(x) for x in raw))
    if kind == "fontFamily" and isinstance(raw, list):
        return ", ".join(f'"{x}"' if " " in x else x for x in raw)
    return str(raw)


def kebab(name):
    name = name.replace(".", "-")
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def css_block(selector, props):
    lines = [f"{selector} {{"] + [f"  {k}: {v};" for k, v in props] + ["}"]
    return "\n".join(lines)


def theme_props(theme):
    out = []
    for key, node in theme.items():
        if key.startswith("$"):
            continue
        out.append((f"--team1-{kebab(key)}", value(node)))
    return out


SHADCN_ALIASES = (
    ("--background", "var(--team1-background)"),
    ("--foreground", "var(--team1-text-body)"),
    ("--card", "var(--team1-surface)"),
    ("--card-foreground", "var(--team1-text-body)"),
    ("--popover", "var(--team1-surface-raised)"),
    ("--popover-foreground", "var(--team1-text-body)"),
    ("--primary", "var(--team1-red-500)"),
    ("--primary-foreground", "var(--team1-text-on-brand)"),
    ("--secondary", "var(--team1-surface)"),
    ("--secondary-foreground", "var(--team1-text-heading)"),
    ("--muted", "var(--team1-surface)"),
    ("--muted-foreground", "var(--team1-text-muted)"),
    ("--accent", "var(--team1-surface-hover)"),
    ("--accent-foreground", "var(--team1-text-heading)"),
    ("--destructive", "var(--team1-error)"),
    ("--destructive-foreground", "#FFFFFF"),
    ("--border", "var(--team1-border)"),
    ("--input", "var(--team1-input-border)"),
    ("--ring", "var(--team1-focus-ring)"),
    ("--radius", "var(--team1-radius-sm)"),
)


def compat_props(g, w):
    """Deprecated 2.x names mapped onto 3.0.0 values (removal planned for 4.0.0)."""
    out = [
        ("--team1-brand", "var(--team1-red)"),
        ("--team1-brand-hover", "var(--team1-red-600)"),
        ("--team1-brand-gradient-end", "var(--team1-red-gradient-end)"),
    ]
    acc = g["color"]["accent"]
    for key in ("avaBlue", "avaBlueHover", "secondaryBlue", "secondaryBlueHover"):
        out.append((f"--team1-{kebab(key)}", value(acc[key]).lower()))
    for mode in ("dark", "light"):
        for key, node in g["color"][mode].items():
            if not key.startswith("$"):
                out.append((f"--team1-{mode}-{kebab(key)}", value(node).lower()))
    for key in ("info", "featured"):
        out.append((f"--team1-{key}", value(g["color"]["status"][key])))
    out += [
        ("--team1-font-alternative", f'"{value(g["typography"]["alternative"]["family"])}", sans-serif'),
        ("--team1-font-weight-body", value(g["typography"]["body"]["weight"])),
    ]
    for name, node in g["typography"]["scale"].items():
        if "$value" in node:
            old = {"bodyLarge": "body-large-size", "body": "body-size", "bodySmall": "body-small-size", "caption": "caption-size"}.get(name, f"heading-{name}")
            out.append((f"--team1-{old}", f"var(--team1-font-size-{kebab(name)})"))
        else:
            for bp in node:
                out.append((f"--team1-heading-{name}-{bp}", f"var(--team1-font-size-{name}-{bp})"))
    out += [
        ("--team1-radius-label", "var(--team1-radius-xs)"),
        ("--team1-radius-small", "var(--team1-radius-xs)"),
        ("--team1-radius-control", "var(--team1-radius-sm)"),
        ("--team1-radius-large", "var(--team1-radius-sm)"),
        ("--team1-radius-card", "var(--team1-radius-lg)"),
        ("--team1-radius-project-logo", "var(--team1-radius-sm)"),
        ("--team1-radius-pill", "var(--team1-radius-full)"),
        ("--team1-page-padding-desktop", "var(--team1-padding-desktop)"),
        ("--team1-page-padding-mobile", "var(--team1-padding-mobile)"),
        ("--team1-touch-target", "var(--team1-touch-target-min)"),
        ("--team1-shadow-default", "0 10px 15px -3px rgba(0,0,0,0.1), 0 4px 6px -4px rgba(0,0,0,0.1)"),
        ("--team1-shadow-card-brand", value(w["theme"]["dark"]["shadowCard"])),
        ("--team1-light-shadow", "0 10px 15px -3px rgba(0,0,0,0.08), 0 4px 6px -4px rgba(0,0,0,0.06)"),
        ("--team1-light-shadow-card-brand", value(w["theme"]["light"]["shadowCard"])),
    ]
    return out


def build(tokens):
    meta = tokens["$extensions"]["network.team1"]
    version = meta["version"]
    g, w = tokens["global"], tokens["web"]
    static = []
    for step, node in g["color"]["brand"]["scale"].items():
        static.append((f"--team1-red-{step}", value(node)))
    static.append(("--team1-red", value(g["color"]["brand"]["primary"])))
    static.append(("--team1-red-gradient-end", value(g["color"]["brand"]["gradientEnd"])))
    for key in ("success", "warning", "error"):
        static.append((f"--team1-{key}", value(g["color"]["status"][key])))
    for key in ("avaBlue", "secondaryBlue"):
        static.append((f"--team1-identity-{kebab(key)}", value(g["color"]["accent"][key])))
    wt = w["typography"]
    static += [
        ("--team1-font-heading", value(wt["heading"]["family"])),
        ("--team1-font-body", value(wt["body"]["family"])),
        ("--team1-font-mono", value(wt["mono"]["family"])),
        ("--team1-font-weight-heading", value(wt["heading"]["weight"])),
        ("--team1-font-weight-long-form", value(wt["body"]["weightLongForm"])),
        ("--team1-font-weight-ui", value(wt["body"]["weightUi"])),
        ("--team1-font-weight-ui-strong", value(wt["body"]["weightUiStrong"])),
        ("--team1-line-height-long-form", value(wt["body"]["lineHeightLongForm"])),
        ("--team1-line-height-ui", value(wt["body"]["lineHeightUi"])),
        ("--team1-line-height-heading", value(wt["headingLineHeight"])),
        ("--team1-tracking-heading", value(wt["headingTracking"])),
        ("--team1-meta-size", value(wt["mono"]["metaSize"])),
        ("--team1-meta-tracking", value(wt["mono"]["metaTracking"])),
    ]
    for name, node in g["typography"]["scale"].items():
        if "$value" in node:
            static.append((f"--team1-font-size-{kebab(name)}", value(node)))
        else:
            for bp, sub in node.items():
                static.append((f"--team1-font-size-{name}-{bp}", value(sub)))
    for key, node in w["radius"].items():
        if not key.startswith("$"):
            static.append((f"--team1-radius-{key}", value(node)))
    for key, node in g["spacing"].items():
        static.append((f"--team1-space-{key.replace('.', '-')}", value(node)))
    for key, node in g["zIndex"].items():
        static.append((f"--team1-z-{kebab(key)}", value(node)))
    for key, node in g["responsive"]["breakpoints"].items():
        static.append((f"--team1-breakpoint-{key}", value(node)))
    for key in ("containerMax", "paddingDesktop", "paddingMobile", "touchTargetMin"):
        static.append((f"--team1-{kebab(key)}", value(g["responsive"][key])))
    for key in ("fast", "medium", "slow", "easeStandard", "easeEntrance", "entrance", "entranceOffset", "stagger"):
        static.append((f"--team1-motion-{kebab(key)}", value(g["motion"][key])))
    static += [
        ("--team1-focus-width", value(w["focus"]["width"])),
        ("--team1-focus-offset", value(w["focus"]["offset"])),
    ]
    for key, node in w["state"]["button"].items():
        static.append((f"--team1-button-{kebab(key)}", value(node)))
    static.append(("--team1-card-hover-lift", value(w["state"]["card"]["hoverLift"])))
    for key, node in w["control"].items():
        static.append((f"--team1-control-{kebab(key)}", value(node)))

    dark = theme_props(w["theme"]["dark"])
    light = theme_props(w["theme"]["light"])
    parts = [
        HEADER.format(version=version),
        "/* Static foundations (theme-independent). */",
        css_block(":root", static),
        "",
        "/* Dark is the default theme. An explicit choice uses data-theme=\"dark|light\" (or the .dark/.light class) on <html>. */",
        css_block(':root,\n[data-theme="dark"],\n.dark', [("color-scheme", "dark")] + dark + list(SHADCN_ALIASES)),
        "",
        "/* No explicit choice: follow the operating system only when it asks for light. */",
        "@media (prefers-color-scheme: light) {\n"
        + "\n".join("  " + line for line in css_block(':root:not([data-theme]):not(.dark)', [("color-scheme", "light")] + light).splitlines())
        + "\n}",
        "",
        css_block('[data-theme="light"],\n.light', [("color-scheme", "light")] + light),
        "",
        "/* 2.x variable names, kept as deprecated aliases so existing sites keep rendering while they migrate.",
        "   Scheduled for removal in 4.0.0. New code uses the 3.0.0 names above. Values follow the 3.0.0 decisions",
        "   (for example --team1-radius-card is now 20px and --team1-dark-text-brand is the AA-safe #ec5a64). */",
        css_block(":root", compat_props(g, w)),
        "",
        "/* Inherited presentation master only (profiles.presentationCurrent). Never a global Team1 value. */",
        css_block('[data-team1-profile="presentation-inherited"]', [
            ("--team1-profile-red", "#e84142"),
            ("--team1-profile-theme-accent", "#f5384b"),
            ("--team1-profile-note", '"inherited presentation only; not global Team1 red"'),
        ]),
        "",
        "/* Reduced motion: remove nonessential movement. Components swap scale/translate feedback for colour steps. */",
        "@media (prefers-reduced-motion: reduce) {\n"
        "  *, *::before, *::after {\n"
        "    animation-duration: 0.01ms !important;\n"
        "    animation-iteration-count: 1 !important;\n"
        "    scroll-behavior: auto !important;\n"
        "    transition-duration: 0.01ms !important;\n"
        "  }\n"
        "}",
        "",
        "/* Retired values (migration/linting only, never a palette): "
        + ", ".join(k for k in meta["retired"] if k.startswith("#"))
        + ". */",
        "",
    ]
    css = "\n".join(parts)

    scale = g["color"]["brand"]["scale"]
    tw = [HEADER.format(version=version),
          "/* Import after tailwindcss and design-tokens.css:\n   @import \"tailwindcss\";\n   @import \"./design-tokens.css\";\n   @import \"./tailwind-theme.css\";\n   Core palette, radius, font and shadow namespaces are reset, so off-system values (Tailwind blue, rounded-md, shadow-lg) do not exist. */",
          "@theme {",
          "  --color-*: initial;",
          "  --color-white: #FFFFFF;",
          "  --color-black: #000000;",
          "  --color-transparent: transparent;"]
    tw += [f"  --color-brand-{k}: {value(v)};" for k, v in scale.items()]
    tw += [f"  --color-brand: {value(g['color']['brand']['primary'])};",
           "  --color-success: var(--team1-success);",
           "  --color-warning: var(--team1-warning);",
           "  --color-error: var(--team1-error);",
           "",
           "  --font-*: initial;",
           "  --font-heading: var(--team1-font-heading);",
           "  --font-sans: var(--team1-font-body);",
           "  --font-mono: var(--team1-font-mono);",
           "",
           "  --radius-*: initial;"]
    tw += [f"  --radius-{k}: {value(v)};" for k, v in w["radius"].items() if not k.startswith("$") and k != "full"]
    tw += ["  /* Pill: use Tailwind's built-in rounded-full. */",
           "",
           "  --shadow-*: initial;",
           "  --shadow-none: 0 0 #0000;",
           "",
           "  --ease-entrance: var(--team1-motion-ease-entrance);",
           "  --ease-standard: var(--team1-motion-ease-standard);",
           "  --animate-fade-in-up: team1-fade-in-up 400ms var(--team1-motion-ease-entrance) both;",
           "  @keyframes team1-fade-in-up {",
           "    from { opacity: 0; transform: translateY(var(--team1-motion-entrance-offset)); }",
           "    to { opacity: 1; transform: none; }",
           "  }",
           "}",
           "",
           "/* Theme-dependent roles resolve at runtime through the custom properties. */",
           "@theme inline {"]
    roles = [k for k in w["theme"]["dark"] if not k.startswith("$") and not k.startswith("shadow")]
    for k in roles:
        if k.startswith("text"):
            # textHeading -> fg-heading (utility: text-fg-heading)
            tw.append(f"  --color-fg-{kebab(k[4:])}: var(--team1-{kebab(k)});")
        else:
            tw.append(f"  --color-{kebab(k)}: var(--team1-{kebab(k)});")
    tw += ["  --color-line: var(--team1-border);",
           "  --color-line-strong: var(--team1-border-strong);"]
    emitted = {line.split(":")[0].strip() for line in tw}
    for name, _ in SHADCN_ALIASES:
        if name != "--radius" and f"--color-{name[2:]}" not in emitted:
            tw.append(f"  --color-{name[2:]}: var({name});")
    for k in [k for k in w["theme"]["dark"] if k.startswith("shadow")]:
        tw.append(f"  --shadow-{kebab(k[6:])}: var(--team1-{kebab(k)});")
    tw += ["}", "",
           "/* Theme variants that also honour the OS fallback (no explicit data-theme). Dark is the default. */",
           "@custom-variant theme-light {",
           "  &:where([data-theme=\"light\"] *, .light *) { @slot; }",
           "  @media (prefers-color-scheme: light) {",
           "    &:where(:root:not([data-theme]):not(.dark) *) { @slot; }",
           "  }",
           "}", "",
           "@utility container-page {",
           "  margin-inline: auto;",
           "  width: 100%;",
           "  max-width: var(--team1-container-max);",
           "  padding-inline: var(--team1-padding-mobile);",
           "  @media (width >= 40rem) { padding-inline: var(--team1-padding-desktop); }",
           "}", "",
           "@utility meta {",
           "  font-family: var(--team1-font-mono);",
           "  font-size: var(--team1-meta-size);",
           "  letter-spacing: var(--team1-meta-tracking);",
           "  color: var(--team1-text-muted);",
           "}", "",
           "@utility focus-ring {",
           "  outline: var(--team1-focus-width) solid var(--team1-focus-ring);",
           "  outline-offset: var(--team1-focus-offset);",
           "}", "",
           "@layer base {",
           "  * { border-color: var(--team1-border); }",
           "  body {",
           "    background: var(--team1-background);",
           "    color: var(--team1-text-body);",
           "    font-family: var(--team1-font-body);",
           "    font-weight: var(--team1-font-weight-long-form);",
           "    line-height: var(--team1-line-height-long-form);",
           "  }",
           "  h1, h2, h3, h4, h5, h6 {",
           "    font-family: var(--team1-font-heading);",
           "    font-weight: var(--team1-font-weight-heading);",
           "    line-height: var(--team1-line-height-heading);",
           "    letter-spacing: var(--team1-tracking-heading);",
           "    color: var(--team1-text-heading);",
           "  }",
           "  :focus-visible {",
           "    outline: var(--team1-focus-width) solid var(--team1-focus-ring);",
           "    outline-offset: var(--team1-focus-offset);",
           "  }",
           "}", ""]
    return css, "\n".join(tw)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    root = Path(args[0]) if args else Path(__file__).resolve().parents[1]
    tokens = json.loads((root / "tokens" / "design-tokens.json").read_text(encoding="utf-8"))
    css, tw = build(tokens)
    outputs = {root / "tokens" / "design-tokens.css": css, root / "tokens" / "tailwind-theme.css": tw}
    stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if check:
        for path in stale:
            print(f"generated token file is out of date: {path.relative_to(root)}")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
